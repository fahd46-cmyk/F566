package com.example.ui

import android.util.Base64
import java.security.SecureRandom

data class WireGuardProfileDraft(
    val profileName: String = "Jissr-Dubai-WG0",
    // [Interface]
    val interfacePrivateKey: String = "oG8xK4mP9qR2vL7nZ1wC5tY3bF6hJ0sA4dG8kM2pQ1E=",
    val interfacePublicKey: String = "JissrClientPub9xK4mP8qR2vL7nZ1wC5tY3bF6hJ0s=",
    val interfaceAddress: String = "10.88.11.2/24",
    val interfaceDns: String = "1.1.1.1, 1.0.0.1",
    val interfaceMtu: String = "1420",
    val interfaceListenPort: String = "51820",
    // [Peer]
    val peerPublicKey: String = "JissrDXB9xK4mP8qR2vL7nZ1wC5tY3bF6hJ0sA4dG8k=",
    val peerPresharedKey: String = "",
    val peerEndpoint: String = "1.1.1.1:443",
    val peerAllowedIps: String = "0.0.0.0/0, ::/0",
    val peerPersistentKeepalive: String = "25"
) {
    fun toConfString(): String = buildString {
        appendLine("# Name = ${profileName.ifBlank { "Jissr-WG0" }}")
        appendLine("# Generated by Jissr VPN Config Studio")
        appendLine("[Interface]")
        appendLine("PrivateKey = ${interfacePrivateKey.trim()}")
        appendLine("Address = ${interfaceAddress.trim()}")
        if (interfaceDns.isNotBlank()) {
            appendLine("DNS = ${interfaceDns.trim()}")
        }
        if (interfaceMtu.isNotBlank()) {
            appendLine("MTU = ${interfaceMtu.trim()}")
        }
        if (interfaceListenPort.isNotBlank()) {
            appendLine("ListenPort = ${interfaceListenPort.trim()}")
        }
        appendLine()
        appendLine("[Peer]")
        appendLine("PublicKey = ${peerPublicKey.trim()}")
        if (peerPresharedKey.isNotBlank()) {
            appendLine("PresharedKey = ${peerPresharedKey.trim()}")
        }
        appendLine("Endpoint = ${peerEndpoint.trim()}")
        appendLine("AllowedIPs = ${peerAllowedIps.trim()}")
        if (peerPersistentKeepalive.isNotBlank() && peerPersistentKeepalive.trim() != "0") {
            append("PersistentKeepalive = ${peerPersistentKeepalive.trim()}")
        }
    }

    fun validate(isArabic: Boolean): List<String> {
        val issues = mutableListOf<String>()
        if (interfacePrivateKey.trim().length < 40) {
            issues.add(
                if (isArabic) "المفتاح الخاص (PrivateKey) يجب أن يكون بصيغة Base64 (44 حرفاً)"
                else "Interface PrivateKey should be a 44-character Base64 key"
            )
        }
        if (!interfaceAddress.contains("/")) {
            issues.add(
                if (isArabic) "عنوان الواجهة (Address) يجب أن يتضمن قناع الشبكة مثل /24"
                else "Interface Address must include CIDR prefix (e.g. /24)"
            )
        }
        if (peerPublicKey.trim().length < 40) {
            issues.add(
                if (isArabic) "المفتاح العام للخادم (Peer PublicKey) غير مكتمل"
                else "Peer PublicKey should be a valid Base64 key"
            )
        }
        if (!peerEndpoint.contains(":")) {
            issues.add(
                if (isArabic) "عنوان الخادم (Endpoint) يجب أن يكون بصيغة host:port"
                else "Peer Endpoint must be formatted as host:port"
            )
        }
        return issues
    }

    companion object {
        private val secureRandom = SecureRandom()

        fun generateWireGuardKey(): String {
            val bytes = ByteArray(32)
            secureRandom.nextBytes(bytes)
            // WireGuard Curve25519 clamping
            bytes[0] = (bytes[0].toInt() and 248).toByte()
            bytes[31] = (bytes[31].toInt() and 127).toByte()
            bytes[31] = (bytes[31].toInt() or 64).toByte()
            return Base64.encodeToString(bytes, Base64.NO_WRAP)
        }

        fun parseFromConf(rawConf: String, fallbackName: String = "Imported-WG0"): WireGuardProfileDraft {
            var currentSection = ""
            var name = fallbackName
            var privKey = ""
            var address = "10.88.11.2/24"
            var dns = "1.1.1.1"
            var mtu = "1420"
            var listenPort = ""
            var peerPub = ""
            var psk = ""
            var endpoint = "1.1.1.1:443"
            var allowedIps = "0.0.0.0/0, ::/0"
            var keepalive = "25"

            rawConf.lineSequence().forEach { rawLine ->
                val line = rawLine.trim()
                if (line.startsWith("#")) {
                    val commentContent = line.removePrefix("#").trim()
                    if (commentContent.startsWith("Name", ignoreCase = true) && commentContent.contains("=")) {
                        name = commentContent.substringAfter("=").trim()
                    }
                    return@forEach
                }
                if (line.isEmpty()) return@forEach

                if (line.startsWith("[") && line.endsWith("]")) {
                    currentSection = line.lowercase()
                    return@forEach
                }

                val eqIndex = line.indexOf('=')
                if (eqIndex > 0) {
                    val key = line.substring(0, eqIndex).trim().lowercase()
                    val value = line.substring(eqIndex + 1).trim()
                    when (currentSection) {
                        "[interface]" -> when (key) {
                            "privatekey" -> privKey = value
                            "address" -> address = value
                            "dns" -> dns = value
                            "mtu" -> mtu = value
                            "listenport" -> listenPort = value
                        }
                        "[peer]" -> when (key) {
                            "publickey" -> peerPub = value
                            "presharedkey" -> psk = value
                            "endpoint" -> endpoint = value
                            "allowedips" -> allowedIps = value
                            "persistentkeepalive" -> keepalive = value
                        }
                    }
                }
            }

            return WireGuardProfileDraft(
                profileName = name.ifBlank { fallbackName },
                interfacePrivateKey = privKey.ifBlank { generateWireGuardKey() },
                interfacePublicKey = generateWireGuardKey(),
                interfaceAddress = address,
                interfaceDns = dns,
                interfaceMtu = mtu,
                interfaceListenPort = listenPort,
                peerPublicKey = peerPub.ifBlank { generateWireGuardKey() },
                peerPresharedKey = psk,
                peerEndpoint = endpoint,
                peerAllowedIps = allowedIps,
                peerPersistentKeepalive = keepalive
            )
        }
    }
}
